export async function seedScholarshipsCatalog(): Promise<number> {
  let seededCount = 0;
  for (const item of VERIFIED_SCHOLARSHIPS_SEED) {
    const existing = await prisma.scholarship.findUnique({
      where: { slug: item.slug },
    });

    if (!existing) {
      await prisma.scholarship.create({
        data: {
          slug: item.slug,
          name: item.name,
          provider: item.provider,
          country: item.country,
          destinationCountry: item.destinationCountry,
          department: item.department,
          specialization: item.specialization,
          studyLevel: item.studyLevel,
          awardAmount: item.awardAmount,
          awardCurrency: item.awardCurrency,
          awardType: item.awardType,
          awardDetails: item.awardDetails,
          eligibilityDescription: item.eligibilityDescription,
          minPercentageRequirement: item.minPercentageRequirement,
          eligibleBoards: item.eligibleBoards ? JSON.stringify(item.eligibleBoards) : null,
          requiredCitizenship: item.requiredCitizenship,
          genderRequirement: item.genderRequirement,
          incomeCeiling: item.incomeCeiling,
          incomeCurrency: item.incomeCurrency,
          requiredExams: item.requiredExams ? JSON.stringify(item.requiredExams) : null,
          applicationDeadline: item.applicationDeadline,
          applicationUrl: item.applicationUrl,
          sourceInfo: item.sourceInfo,
          isActive: item.isActive,
          isPublished: item.isPublished,
        },
      });
      seededCount++;
    }
  }
  return seededCount;
}
